# Figures for the SNN2AC memo on SNNModels bugs (requested by the SNN2AC session, 2026-10-05).
#  - stdp_gerstner_kernel.png: STDPGerstner weight change per pre/post pair, SNNModels 1.8.1 vs
#    >= 1.8.2, for SNN2AC's `STDPExc` parameters and for the library default. Computed from the
#    update equations of the two versions (no simulation):
#      1.8.1 (src/connections/sparse_plasticity/STDP_traces.jl@614cfca): traces jump by A_pre / A_post,
#        Δw = A_pre * trace_pre at a post spike and A_post * trace_post at a pre spike
#        -> A_pre^2 e^{-Δt/τpre} (pre before post), A_post^2 e^{-|Δt|/τpost} (post before pre).
#      >= 1.8.2: traces jump by 1 -> A_pre e^{-Δt/τpre}, A_post e^{-|Δt|/τpost}
#        (validated against Brian2, Auryn and the analytic kernel, validation/stdp/).
#  - sparse_generator.png: connectivity generated by the 1.8.1 dense generator
#    (kept as sparse_matrix_dense_legacy) and the >= 1.8.2 CSC generator: in-degree and weight
#    distributions, and stored autapses of a recurrent connection.
# Usage: julia --project=<env with SNNModels >= 1.9, SNNPlots, CairoMakie, JLD2> memo_figures.jl
using SNNModels, SNNPlots, CairoMakie, JLD2, SparseArrays, LinearAlgebra, Random, Statistics
SNNPlots.@makie_default
@load_units

const DIR = @__DIR__
mkpath(joinpath(DIR, "figures")); mkpath(joinpath(DIR, "data"))
const OLD, NEW, INTENDED = colorant"#D55E00", colorant"#0072B2", colorant"#8c8c8c"

# ------------------------------------------------------------------ STDPGerstner kernel
kernel(Δt, Apre, Apost, τpre, τpost; squared) = Δt > 0 ?
    (squared ? Apre^2 : Apre) * exp(-Δt / τpre) :
    (squared ? Apost^2 : Apost) * exp(Δt / τpost)
Δts = filter(!iszero, collect(-100.0:0.5:100.0))
sets = [("SNN2AC STDPExc (A_pre 4e-4, A_post +1.4e-3)", 4e-4, 1.4e-3),
        ("library default (A_pre 1e-4, A_post -1e-4 from 1.8.2; +1e-4 in 1.8.1)", 1e-4, -1e-4)]
kern = Dict{String,Any}()
for (name, Apre, Apost) in sets
    Apost_old = name[1:6] == "SNN2AC" ? Apost : abs(Apost)       # 1.8.1 default was +1e-4
    kern[name] = (old = [kernel(t, Apre, Apost_old, 20, 20; squared = true) for t in Δts],
                  new = [kernel(t, Apre, Apost, 20, 20; squared = false) for t in Δts],
                  intended = [kernel(t, Apre, -abs(Apost), 20, 20; squared = false) for t in Δts])
end
jldsave(joinpath(DIR, "data", "stdp_gerstner_kernel.jld2"); Δts, kern)

fig = Figure(size = (1300, 470))
for (k, (name, Apre, Apost)) in enumerate(sets)
    d = kern[name]
    ax = Axis(fig[1, k], title = name, titlesize = 12, xlabel = "Δt = t_post − t_pre (ms)",
              ylabel = k == 1 ? "Δw per pair (pF)" : "")
    hlines!(ax, [0], color = :black, linewidth = 0.5)
    lines!(ax, Δts, d.new, color = NEW, linewidth = 2, label = "≥ 1.8.2: A applied once")
    k == 1 && lines!(ax, Δts, d.intended, color = INTENDED, linestyle = :dash, linewidth = 1.5,
                     label = "≥ 1.8.2 with A_post = −1.4e-3 (classical LTD)")
    lines!(ax, Δts, d.old, color = OLD, linewidth = 2, label = "1.8.1: A², sign of A_post lost")
    axislegend(ax, position = :lt, labelsize = 10)
    mx = maximum(abs, d.old)
    text!(ax, 0.98, 0.04, space = :relative, align = (:right, :bottom), fontsize = 10,
          text = "1.8.1 peak $(round(mx, sigdigits = 2)) pF, $(round(Int, maximum(abs, d.new) / mx))× smaller")
end
Label(fig[0, 1:2], "STDPGerstner weight change per pre/post pair, from the update equations of SNNModels 1.8.1 and ≥ 1.8.2 (τpre = τpost = 20 ms)",
      fontsize = 13, halign = :left)
save(joinpath(DIR, "figures", "stdp_gerstner_kernel.png"), fig, px_per_unit = 2)

# ------------------------------------------------------------------ sparse generator
N, p, μ, σ = 2000, 0.1, 10.0, 2.0
Random.seed!(1); Wold = SNNModels.sparse_matrix_dense_legacy(N, N; p = p, μ = μ, σ = σ, rule = :Bernoulli)
Wold = SparseMatrixCSC{Float32,Int}(Wold); Wold[diagind(Wold)] .= 0       # 1.8.1 SpikingSynapse(pre, pre)
Random.seed!(1); Wnew = SNNModels.sparse_matrix(N, N; p = p, μ = μ, σ = σ, rule = :Bernoulli)
SNNModels.remove_autapses!(Wnew)                                             # >= 1.8.2
stored_diag(W) = count(i -> any(==(i), rowvals(W)[nzrange(W, i)]), 1:size(W, 2))
gen = (indeg_old = vec(sum(Wold .!= 0, dims = 2)), indeg_new = vec(sum(Wnew .!= 0, dims = 2)),
       w_old = nonzeros(Wold)[nonzeros(Wold) .> 0], w_new = nonzeros(Wnew),
       nnz_old = nnz(Wold), nnz_new = nnz(Wnew), diag_old = stored_diag(Wold), diag_new = stored_diag(Wnew),
       same_entries = count(!iszero, Wold .* Wnew .!= 0))
jldsave(joinpath(DIR, "data", "sparse_generator.jld2"); gen, N, p, μ, σ)

fig = Figure(size = (1300, 420))
ax = Axis(fig[1, 1], title = "in-degree per neuron", xlabel = "in-degree", ylabel = "neurons")
stephist!(ax, gen.indeg_old, bins = 40, color = OLD, linewidth = 2, label = "1.8.1 dense generator")
stephist!(ax, gen.indeg_new, bins = 40, color = NEW, linewidth = 2, linestyle = :dash, label = "≥ 1.8.2 CSC generator")
axislegend(ax, position = :lt, labelsize = 10)
ax = Axis(fig[1, 2], title = "weights of existing synapses", xlabel = "w (pF)", ylabel = "synapses")
stephist!(ax, gen.w_old, bins = 60, color = OLD, linewidth = 2)
stephist!(ax, gen.w_new, bins = 60, color = NEW, linewidth = 2, linestyle = :dash)
ax = Axis(fig[1, 3], title = "stored autapses (recurrent connection)", ylabel = "count",
          xticks = (1:2, ["1.8.1", "≥ 1.8.2"]))
barplot!(ax, 1:2, [gen.diag_old, gen.diag_new], color = [OLD, NEW])
text!(ax, 1, gen.diag_old, text = "$(gen.diag_old) zero-weight\nentries", align = (:center, :bottom), fontsize = 10)
text!(ax, 2, gen.diag_new, text = "0", align = (:center, :bottom), fontsize = 10)
ylims!(ax, 0, 1.4 * max(gen.diag_old, 1))
Label(fig[0, 1:3], "Bernoulli connectivity N = $N × $N, p = $p, w ~ Normal($μ, $σ), same seed: same statistics, different realisation " *
      "(entries in common: $(gen.same_entries) of $(gen.nnz_new))", fontsize = 13, halign = :left)
save(joinpath(DIR, "figures", "sparse_generator.png"), fig, px_per_unit = 2)
println(gen.nnz_old, " / ", gen.nnz_new, " synapses; stored diagonal ", gen.diag_old, " / ", gen.diag_new,
        "; mean in-degree ", mean(gen.indeg_old), " / ", mean(gen.indeg_new), "; common entries ", gen.same_entries)
